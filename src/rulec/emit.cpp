// A C++ string literal of bytes: valid UTF-8 as is, other bytes and quotes escaped (octal
// escapes end after three digits).
std::string CppString(std::string_view s) {
    std::string out = "\"";
    for (std::size_t i = 0; i < s.size(); i++) {
        const unsigned char c = static_cast<unsigned char>(s[i]);
        std::size_t n = c < 0x80 ? 1 : c >> 5 == 6 ? 2 : c >> 4 == 14 ? 3 : c >> 3 == 30 ? 4 : 0;
        bool valid = n > 0 && i + n <= s.size();
        for (std::size_t k = 1; valid && k < n; k++) valid = (static_cast<unsigned char>(s[i + k]) & 0xc0) == 0x80;
        if (c == '"' || c == '\\') {
            out += '\\';
            out += static_cast<char>(c);
        } else if (valid && (c >= 0x20 && c != 0x7f) && c != '?') {
            out.append(s.substr(i, n));
            i += n - 1;
        } else {
            char buf[8];
            std::snprintf(buf, sizeof buf, "\\%03o", c);
            out += buf;
        }
    }
    return out + "\"";
}

std::string Name(const Rule& r) { return std::string("Rule") + r.kind + std::to_string(r.index); }

// depth: the number of all(...) around e; their values are a<i>, then a1_<i>, a2_<i> inside.
void Expression(std::string& out, const Expr& e, NodeKind parent, int depth = 0) {
    if (e.kind == NodeKind::Atom) {
        const OpInfo& o = Info(e.op);
        static const char* const kNames[] = {
            "SrcEq",  "SrcNe",   "SrcEqW", "DstEq",  "DstNe",       "DstSet",       "DstSetW",
            "PumsaEq", "PumsaNe", "AttrEq", "AttrNe", "AttrMinusEq", "AttrMinusEqW", "GramEq",
            "GramNe", "GramMinusEq", "GobiSrcEq", "GobiSrcNe", "GobiDstEq", "GobiDstSet", "GobiDstSetW",
            "GobiPumsaEq", "GobiAttrEq", "GobiAttrMinusEq", "GobiGramEq", "GobiGramNe"};
        out += kNames[static_cast<int>(e.op)];
        out += "(p, " + std::to_string(e.delta) + ", ";
        out += o.word ? std::to_string(e.rightDelta) : CppString(e.literal) + "sv";
        out += ')';
        return;
    }
    if (e.children.empty()) {
        out += e.kind == NodeKind::Or ? "false" : "true";
        return;
    }
    if (e.kind == NodeKind::AndAll) {
        const std::string a = depth == 0 ? "a" : "a" + std::to_string(depth) + "_";
        out += "[&] {";
        for (std::size_t i = 0; i < e.children.size(); i++) {
            out += " const bool " + a + std::to_string(i) + " = ";
            Expression(out, e.children[i], NodeKind::AndAll, depth + 1);
            out += ';';
        }
        out += " return ";
        for (std::size_t i = 0; i < e.children.size(); i++) out += (i ? " && " : "") + a + std::to_string(i);
        out += "; }()";
        return;
    }
    const bool parens = parent != NodeKind::AndAll && parent != NodeKind::Atom;
    if (parens) out += '(';
    for (std::size_t i = 0; i < e.children.size(); i++) {
        if (i > 0) out += e.kind == NodeKind::Or ? " ||\n           " : " && ";
        Expression(out, e.children[i], e.kind, depth);
    }
    if (parens) out += ')';
}

void Function(std::string& out, const Rule& r) {
    File one;
    (r.kind == 'L' ? one.local : one.global).push_back(r);
    one.local.empty() ? one.global[0].tests.clear() : one.local[0].tests.clear();
    const std::string readable = PrintReadable(one);
    for (std::size_t start = 0; start < readable.size();) {
        const std::size_t end = readable.find('\n', start);
        out += "// " + readable.substr(start, end - start) + "\n";
        start = end + 1;
    }
    out += "bool " + Name(r) + "([[maybe_unused]] Item* p) {\n    return ";
    Expression(out, r.body, NodeKind::Atom);
    out += ";\n}\n\n";
}

std::string Hash(uint64_t h) {
    char buf[32];
    std::snprintf(buf, sizeof buf, "0x%016llxull", static_cast<unsigned long long>(h));
    return buf;
}

