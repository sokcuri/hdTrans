std::string EmitCpp(const File& file, const Source& source, int first, int last, bool globals) {
    std::string out =
        "// Generated by hdrulec from src/core/rules/*.txt; do not edit. Regenerate with\n"
        "// hdrulec cpp (docs/rule-compiler.md).\n"
        "#include \"core/rules/compiled.h\"\n\n"
        "namespace hdTrans::rules::compiled {\n\n"
        "using namespace std::string_view_literals;\n\n";
    std::string localTable, globalTable;
    for (const Rule& r : file.local) {
        if (r.index < first || r.index > last) {
            if (r.index < first) localTable += "    {nullptr, 0},\n";
            continue;
        }
        Function(out, r);
        localTable += "    {" + Name(r) + ", " + Hash(rules::compiled::RecordHash(std::string_view(source.text).substr(r.offset, r.length))) + "},\n";
    }
    if (globals) {
        for (const Rule& r : file.global) {
            Function(out, r);
            globalTable += "    {" + Name(r) + ", " + Hash(rules::compiled::RecordHash(std::string_view(source.text).substr(r.offset, r.length))) + "},\n";
        }
    }
    out += "namespace {\n\n";
    out += "constexpr CompiledRule kLocal[] = {\n" + (localTable.empty() ? "    {nullptr, 0},\n" : localTable) + "};\n\n";
    out += "constexpr CompiledRule kGlobal[] = {\n" + (globalTable.empty() ? "    {nullptr, 0},\n" : globalTable) + "};\n\n";
    out += "}  // namespace\n\n";
    out += "std::span<const CompiledRule> LocalRules() { return kLocal; }\n\n";
    out += "std::span<const CompiledRule> GlobalRules() { return kGlobal; }\n\n";
    out += "}  // namespace hdTrans::rules::compiled\n";
    return out;
}

