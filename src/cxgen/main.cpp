// hdcxgen: compiles the builtin construction table at build time.
//   hdcxgen OUT
// writes OUT, a C++ source defining CompiledConstructions() as the bytes of
// WriteConstructions(ParseBuiltinConstructions()), only when they change. It links the library's objects
// with no_table.cpp, so the table it reads is the one parsed from constructions.tsv.
// Exit: 0 written or unchanged, 1 the table does not read back or OUT cannot be written, 2 usage.
#include <cstdio>
#include <fstream>
#include <iterator>
#include <sstream>
#include <string>
#include <vector>

#include "core/word/constructions.h"

int main(int argc, char** argv) {
    using namespace hdTrans::word::internal;
    if (argc != 2) {
        std::fputs("usage: hdcxgen OUT\n", stderr);
        return 2;
    }
    const std::vector<uint8_t> bytes = WriteConstructions(ParseBuiltinConstructions());
    ConstructionTable back;
    if (!ReadConstructions(bytes, back) || WriteConstructions(back) != bytes) {
        std::fputs("hdcxgen: the construction table does not read back\n", stderr);
        return 1;
    }
    std::string out =
        "// Generated by hdcxgen from constructions.tsv; do not edit.\n"
        "#include \"core/word/constructions.h\"\n\n"
        "namespace hdTrans::word::internal {\n\nnamespace {\n\n"
        "constexpr uint8_t kTable[] = {\n";
    for (std::size_t i = 0; i < bytes.size(); i++) {
        out += std::to_string(bytes[i]);
        out += (i + 1) % 32 == 0 || i + 1 == bytes.size() ? ",\n" : ",";
    }
    out += "};\n\n}  // namespace\n\nstd::span<const uint8_t> CompiledConstructions() { return kTable; }\n\n"
           "}  // namespace hdTrans::word::internal\n";
    {
        std::ifstream in(argv[1], std::ios::binary);
        std::ostringstream old;
        old << in.rdbuf();
        if (in && old.str() == out) return 0;
    }
    std::ofstream file(argv[1], std::ios::binary | std::ios::trunc);
    file << out;
    file.close();
    if (!file) {
        std::fprintf(stderr, "hdcxgen: cannot write %s\n", argv[1]);
        return 1;
    }
    return 0;
}
