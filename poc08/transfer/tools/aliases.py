#!/usr/bin/env python3
"""Writes data/alias.tsv: each kana form used in the cx tables → the analyzer lemma(s) it stands for.

  aliases.py DATA_DIR      (needs fugashi + unidic, UniDic 3.1; build-time tool only)

A table may write わけ, もらう or いる; the analyzer gives the lemmas 訳, 貰う, 居る. The alias table lets the
rows stay readable while matching stays on lemmas (no surface tests at run time).
"""
import glob
import os
import re
import sys

import fugashi
import unidic

T = fugashi.Tagger('-d ' + unidic.DICDIR + ' -r ' + unidic.DICDIR + '/mecabrc')
KANA = re.compile(r'^[ぁ-ゟ゠-ヿー]+$')


CONTENT = ('動詞', '形容詞', '名詞', '形状詞', '副詞')


def lemmas_of(form):
    """The lemma of a kana content word, when the analyzer reads it the same way alone and before 。."""
    found = []
    for frame in ('{}', '{}。'):
        lem = None
        for w in T(frame.format(form)):
            if w.surface == form and w.feature.pos1 in CONTENT:
                lem = w.feature.lemma or form
                lem = lem.split('-')[0] if '-' in lem and not lem.startswith('-') else lem
        found.append(lem)
    if found[0] and found[0] == found[1] and found[0] != form and len(form) >= 2:
        return {found[0]}
    return set()


def main():
    data = sys.argv[1]
    forms = set()
    for p in glob.glob(os.path.join(data, 'cx', '*.tsv')):
        if p.endswith('.cases.tsv'):
            continue
        for line in open(p, encoding='utf-8'):
            if line.startswith('#') or line.startswith('id\t'):
                continue
            cols = line.rstrip('\n').split('\t')
            if len(cols) < 3:
                continue
            for atom in cols[1].split():
                atom = atom.strip('[]')
                if atom.startswith(('{', '@', '...')):
                    continue
                atom = atom.lstrip('!').split('/')[0]
                forms.update(a for a in atom.split('|') if KANA.match(a))
            for m in re.finditer(r'\.lemma!?=([^ ]+)', cols[2]):
                forms.update(a for a in m.group(1).split('|') if KANA.match(a))
    rows = []
    for f in sorted(forms):
        ls = lemmas_of(f)
        if ls:
            rows.append((f, '|'.join(sorted(ls))))
    with open(os.path.join(data, 'alias.tsv'), 'w', encoding='utf-8') as out:
        out.write('#! alias\n# Generated by tools/aliases.py from the cx tables (UniDic 3.1 lemmas). Do not edit.\n')
        out.write('form\tlemma\n')
        for f, l in rows:
            out.write(f'{f}\t{l}\n')
    print(len(rows), 'aliases', file=sys.stderr)


if __name__ == '__main__':
    main()
