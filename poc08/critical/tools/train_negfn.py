#!/usr/bin/env python3
"""Trains the negation-function classifier the QE gate reads (Japanese side only; no system's output is a
feature). Silver: two blind labelling passes over dev negation points, agreed items kept. Features: the C++
extractor (hd8decide --dump on hdtrans08-ir side IR), so training and use read the same names.

  train_negfn.py ITEMS.jsonl GOLD_A.jsonl GOLD_B.jsonl FEATS.json OUT.tsv [L1]
CV: leave one work out over the game works and caption blocks; test: fiction (other works, out of domain).
Prints accuracy and per-class precision/recall against the W2 rule (clause negFn) on the same items."""
import collections, json, os, random, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lr import SparseLR  # noqa: E402

MERGE = {'INVITE': 'ASK', 'REQUEST': 'ASK', 'CMD': 'ASK', 'VOLIT': 'NOTNEG'}
W2MAP = {'plain': 'PLAIN', 'rhetorical': 'RHET', 'prohibitive': 'PROHIB', 'obligation': 'OBLIG',
         'potential-neg': 'POT', 'double': 'DOUBLE', 'archaic-vol': 'NOTNEG', 'none': 'PLAIN'}
items_f, A_f, B_f, F_f, out_f = sys.argv[1:6]
L1 = float(sys.argv[6]) if len(sys.argv) > 6 else 0.002
items = {json.loads(l)['id']: json.loads(l) for l in open(items_f)}
A = {json.loads(l)['id']: json.loads(l)['label'] for l in open(A_f)}
B = {json.loads(l)['id']: json.loads(l)['label'] for l in open(B_f)}
F = json.load(open(F_f))
rows = []
for i, it in items.items():
    if i in A and i in B and A[i] == B[i] and i in F:
        g = MERGE.get(A[i], A[i])
        rows.append(dict(id=i, gold=g, work=it['work'], split=it['split'], f=F[i]['f']))
print('agreed items', len(rows), collections.Counter(r['split'] for r in rows))
print('classes', collections.Counter(r['gold'] for r in rows).most_common())


def fit(tr):
    X = [r['f'] for r in tr]
    cnt = collections.Counter(x for fs in X for x in fs)
    feats = sorted(x for x, n in cnt.items() if n >= 2)
    cls = sorted(set(r['gold'] for r in tr))
    return SparseLR(l1=L1, iters=500).fit(X, [r['gold'] for r in tr], feats, cls)


def w2(r):
    f = next((x[6:] for x in r['f'] if x.startswith('negfn=')), 'none')
    return W2MAP.get(f, 'PLAIN')


def report(name, rs, pred):
    n = len(rs)
    acc = sum(pred[r['id']] == r['gold'] for r in rs) / n
    accw = sum(w2(r) == r['gold'] for r in rs) / n
    print(f'{name}: n={n} learned {100*acc:.1f}%  W2 rule {100*accw:.1f}%')
    for c in sorted(set(r['gold'] for r in rs) | set(pred[r['id']] for r in rs)):
        tp = sum(pred[r['id']] == c and r['gold'] == c for r in rs)
        p = sum(pred[r['id']] == c for r in rs)
        g = sum(r['gold'] == c for r in rs)
        tpw = sum(w2(r) == c and r['gold'] == c for r in rs)
        pw = sum(w2(r) == c for r in rs)
        print(f'   {c:8s} gold {g:4d}  learned P {100*tp/max(1,p):5.1f} R {100*tp/max(1,g):5.1f}   '
              f'W2 P {100*tpw/max(1,pw):5.1f} R {100*tpw/max(1,g):5.1f}')


train = [r for r in rows if r['split'] != 'test']
test = [r for r in rows if r['split'] == 'test']
works = sorted(set(r['work'] for r in train))
pred = {}
for w in works:
    m = fit([r for r in train if r['work'] != w])
    ho = [r for r in train if r['work'] == w]
    for r, p in zip(ho, m.predict([r['f'] for r in ho])):
        pred[r['id']] = p
report('CV (leave one work out, game + captions)', train, pred)
report('CV, random sample only', [r for r in train if r['split'] == 'train-rand'], pred)
m = fit(train)
for r, p in zip(test, m.predict([r['f'] for r in test])):
    pred[r['id']] = p
report('fiction (out of domain)', test, pred)
mall = fit(rows)
with open(out_f, 'w') as o:
    o.write('#! decider family=neg tau=0 id=negfn@1\n')
    o.write(f'# The function of a Japanese negation (sparse multinomial LR, L1={L1}) over named IR features; trained on\n')
    o.write(f'# {len(rows)} agreed silver items of dev text (two blind passes). Generated by poc08/critical/tools/train_negfn.py;\n')
    o.write('# do not edit by hand. Read by the QE gate as an expectation, never as an override.\n')
    o.write('classes\t' + '\t'.join(mall.cls) + '\n')
    # The always-on feature `bias` and the intercept share the row name `bias` in the table format (the loader
    # reads it as the intercept), so its weight is folded into the intercept here.
    bi = mall.fi.get('bias')
    for j, c in enumerate(mall.cls):
        o.write(f'bias\t{c}\t{float(mall.b[j] + (mall.W[bi, j] if bi is not None else 0)):.4f}\n')
    inv = {i: f for f, i in mall.fi.items()}
    for i in range(mall.W.shape[0]):
        if i == bi:
            continue
        for j, c in enumerate(mall.cls):
            if abs(mall.W[i, j]) > 1e-6:
                o.write(f'{inv[i]}\t{c}\t{float(mall.W[i, j]):.4f}\n')
print('nnz', mall.nnz(), '→', out_f)
