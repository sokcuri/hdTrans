#!/usr/bin/env python3
"""Trains the 'written as a negation' model of the QE gate from human references (no model labels): for each
negation point of the game dev text whose function reads as a plain negation, does the human Korean sentence
contain a negative (안, 못, -지 않다, 없다, 아니다, 말다, 모르다, -ㄹ 수 없다, -기 전)? Lexicalised negations
(申し訳ない → 죄송하다, しか…ない → 만, ないうちに → 전에) come out low.

  train_negreal.py POOL.tsv FEATS.json NEGFN.tsv OUT.tsv      (Kiwi venv python with numpy)"""
import collections, json, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'qe'))
sys.path.insert(0, '/Users/sokcuri/hdwork/v08/X')
import ja, ko, negfn  # noqa: E402
from lr import SparseLR  # noqa: E402

pool_f, feats_f, table_f, out_f = sys.argv[1:5]
pool = [l.rstrip('\n').split('\t') for l in open(pool_f)]
F = json.load(open(feats_f))
T = negfn.Table(table_f)
rows = []
cache = {}
for pid, v in F.items():
    if v['corpus'] != 'gc':
        continue
    p = T.probs(v['f'])
    if p.get('PLAIN', 0) + p.get('NEGCOND', 0) < 0.5:
        continue
    li = v['line']
    jl, ref = pool[li][3], pool[li][4]
    if not ref.strip():
        continue
    src = int(pid.rsplit('@', 1)[1])
    js = ja.sentences(jl)
    si = next((k for k, (a, b) in enumerate(js) if a <= src < b), len(js) - 1)
    if li not in cache:
        cache[li] = ko.analyse(ref)
    ks = cache[li]
    units = [ks[si]] if len(ks) == len(js) else ks
    real = any(u['neg'] or u['pot_neg'] or u.get('before') or u['prohib'] for u in units)
    rows.append(dict(id=pid, work=v['work'], y='NEG' if real else 'NONEG', f=v['f']))
print('points', len(rows), collections.Counter(r['y'] for r in rows))


def fit(tr):
    cnt = collections.Counter(x for r in tr for x in r['f'])
    feats = sorted(x for x, n in cnt.items() if n >= 2)
    return SparseLR(l1=0.0005, iters=500).fit([r['f'] for r in tr], [r['y'] for r in tr], feats, ['NEG', 'NONEG'])


def pneg(m, fs):
    z = m.b.copy()
    for f in fs:
        i = m.fi.get(f)
        if i is not None:
            z = z + m.W[i]
    z -= z.max()
    e = np.exp(z)
    return float(e[0] / e.sum())


works = sorted(set(r['work'] for r in rows))
pred = {}
for w in works:
    m = fit([r for r in rows if r['work'] != w])
    for r in rows:
        if r['work'] == w:
            pred[r['id']] = pneg(m, r['f'])
for th in (0.5, 0.7, 0.8, 0.9):
    sel = [r for r in rows if pred[r['id']] >= th]
    print(f'P(neg) >= {th}: {len(sel)} of {len(rows)} points, of them written as a negation {100*sum(r["y"]=="NEG" for r in sel)/max(1,len(sel)):.1f}%')
low = [r for r in rows if pred[r['id']] < 0.5]
print(f'P(neg) < 0.5: {len(low)} points, written as a negation {100*sum(r["y"]=="NEG" for r in low)/max(1,len(low)):.1f}%')
m = fit(rows)
with open(out_f, 'w') as o:
    o.write('#! decider family=negreal tau=0 id=negreal@1\n')
    o.write('# Whether a human Korean translation writes a Japanese plain negation with a negative word (sparse LR over\n')
    o.write(f'# named IR features), from {len(rows)} negation points of game dev text and their references (no model labels).\n')
    o.write('# Generated by poc08/critical/tools/train_negreal.py; do not edit by hand.\n')
    o.write('classes\tNEG\tNONEG\n')
    bi = m.fi.get('bias')
    for j, c in enumerate(m.cls):
        o.write(f'bias\t{c}\t{float(m.b[j] + (m.W[bi, j] if bi is not None else 0)):.4f}\n')
    inv = {i: f for f, i in m.fi.items()}
    for i in range(m.W.shape[0]):
        if i == bi:
            continue
        for j, c in enumerate(m.cls):
            if abs(m.W[i, j]) > 1e-6:
                o.write(f'{inv[i]}\t{c}\t{float(m.W[i, j]):.4f}\n')
print('→', out_f)
