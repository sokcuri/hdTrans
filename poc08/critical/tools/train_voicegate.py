#!/usr/bin/env python3
"""Trains the voice classifier the QE gate reads (れる/られる: PASSIVE POTENTIAL HONORIFIC SPONTANEOUS), Japanese
features only (the W4 decider is stacked on 0.7.x's own reading, which a gate over any output must not use).
Silver: the W4 game/fiction items (re-read on this IR) plus two blind passes over dev voice points, agreed kept.

  train_voicegate.py W4ROWS.json W4FEATS.tsv ITEMS.jsonl GOLD_A.jsonl GOLD_B.jsonl POOLFEATS.json OUT.tsv"""
import collections, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lr import SparseLR  # noqa: E402

w4rows_f, w4feats_f, items_f, A_f, B_f, poolf_f, out_f = sys.argv[1:8]
rows = []
pts = collections.defaultdict(list)
for l in open(w4feats_f):
    key, tok, fam, src, fs = l.rstrip('\n').split('\t')
    pts[int(key.split(':')[0])].append((int(src), fs.split(' ')))
for r in json.load(open(w4rows_f)):
    c = min(pts.get(r['li'], []), key=lambda p: abs(p[0] - r['b']), default=None)
    if c is None or abs(c[0] - r['b']) > 9:
        continue
    rows.append(dict(id=r['id'], work=r['work'], split=r['split'], gold=r['gold'], f=c[1]))
items = {json.loads(l)['id']: json.loads(l) for l in open(items_f)}
A = {json.loads(l)['id']: json.loads(l)['label'] for l in open(A_f)}
B = {json.loads(l)['id']: json.loads(l)['label'] for l in open(B_f)}
PF = json.load(open(poolf_f))
for i, it in items.items():
    if i in A and i in B and A[i] == B[i] and A[i] != 'NA' and i in PF:
        rows.append(dict(id=i, work=it['work'], split=it['split'], gold=A[i], f=PF[i]['f']))
print('items', len(rows), collections.Counter((r['split'], r['gold']) for r in rows))


def fit(tr):
    cnt = collections.Counter(x for r in tr for x in r['f'])
    feats = sorted(x for x, n in cnt.items() if n >= 2)
    return SparseLR(l1=0.001, iters=500).fit([r['f'] for r in tr], [r['gold'] for r in tr], feats,
                                             sorted(set(r['gold'] for r in tr)))


def report(name, rs, pred):
    n = len(rs)
    print(f'{name}: n={n} acc {100*sum(pred[r["id"]]==r["gold"] for r in rs)/n:.1f}%  (all PASSIVE '
          f'{100*sum(r["gold"]=="PASSIVE" for r in rs)/n:.1f}%)')
    for c in sorted(set(r['gold'] for r in rs)):
        tp = sum(pred[r['id']] == c == r['gold'] for r in rs); p = sum(pred[r['id']] == c for r in rs)
        g = sum(r['gold'] == c for r in rs)
        print(f'   {c:12s} gold {g:4d} P {100*tp/max(1,p):5.1f} R {100*tp/max(1,g):5.1f}')


train = [r for r in rows if r['split'] != 'test']
test = [r for r in rows if r['split'] == 'test']
pred = {}
for w in sorted(set(r['work'] for r in train)):
    m = fit([r for r in train if r['work'] != w])
    ho = [r for r in train if r['work'] == w]
    for r, p in zip(ho, m.predict([r['f'] for r in ho])):
        pred[r['id']] = p
report('CV (leave one work out)', train, pred)
m = fit(train)
for r, p in zip(test, m.predict([r['f'] for r in test])):
    pred[r['id']] = p
report('fiction (out of domain)', test, pred)
m = fit(rows)
with open(out_f, 'w') as o:
    o.write('#! decider family=voice tau=0 id=voicegate@1\n')
    o.write(f'# The voice of れる/られる for the QE gate (sparse multinomial LR, Japanese IR features only), from {len(rows)}\n')
    o.write('# agreed silver items. Generated by poc08/critical/tools/train_voicegate.py; do not edit by hand.\n')
    o.write('classes\t' + '\t'.join(m.cls) + '\n')
    bi = m.fi.get('bias')
    for j, c in enumerate(m.cls):
        o.write(f'bias\t{c}\t{float(m.b[j] + (m.W[bi, j] if bi is not None else 0)):.4f}\n')
    inv = {i: f for f, i in m.fi.items()}
    for i in range(m.W.shape[0]):
        if i == bi:
            continue
        for j, c in enumerate(m.cls):
            if abs(m.W[i, j]) > 1e-6:
                o.write(f'{inv[i]}\t{c}\t{float(m.W[i, j]):.4f}\n')
print('→', out_f)
