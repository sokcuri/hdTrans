#!/usr/bin/env python3
"""Proper nouns that human translations do NOT write by their reading (日本 → 일본, 中国 → 중국), from the game dev
text and its references: per surface, how often the reference holds the reading's transliteration. The gate
skips the name check for surfaces seen >= 3 times and transliterated in < half of them.
  build_names.py POOL.tsv [--exclude LINES] IRDIR... > names.tsv   (LINES: pool line indexes to leave out)"""
import collections, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'qe'))
import ja, names  # noqa: E402
pool = [l.rstrip('\n').split('\t') for l in open(sys.argv[1])]
args = sys.argv[2:]
skip = set()
if args and args[0] == '--exclude':
    skip = {int(x) for x in open(args[1]).read().split()}
    args = args[2:]
seen, hit = collections.Counter(), collections.Counter()
li = 0
for d in args:
    for rec in ja.load_ir(os.path.join(d, 'ir.jsonl')):
        row = pool[li]
        li += 1
        if rec is None or row[0] != 'gc' or not row[4].strip() or li - 1 in skip:
            continue
        for nm in ja.names(rec, all_kinds=True):
            seen[nm['surf']] += 1
            hit[nm['surf']] += names.present(dict(nm, surf='\0'), row[4])
print('#! names\n# surface\tseen\ttransliterated (game dev references); generated by build_names.py')
for s, n in seen.most_common():
    if n >= 3:
        print(f'{s}\t{n}\t{hit[s]}')
