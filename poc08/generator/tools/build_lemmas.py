#!/usr/bin/env python3
"""Builds data/ko/lemmas.tsv (lemma → pos) from the 0.7.x Korean marker families in dicts/.

usage: python3 -I tools/build_lemmas.py REPO_ROOT > poc08/generator/data/ko/lemmas.tsv
The class is not stored: G infers it from stems.tsv and classrules.tsv. Only the pos is taken, by
majority over the dictionary rows that use the lemma.
"""
import collections, glob, re, sys

root = sys.argv[1]
fam = {}
src = open(root + '/src/core/output/ko_families_gen.cpp', encoding='utf-8').read()
for k, st, pos, cl in re.findall(r'\{"([&$%]..@)", "([^"]*)", Pos::(\w+), Class::(\w+),', src):
    fam[k] = (st, pos, cl)
cnt = collections.defaultdict(collections.Counter)
for f in sorted(glob.glob(root + '/dicts/*.tsv')):
    for line in open(f, encoding='utf-8'):
        if line.startswith('#'):
            continue
        cols = line.rstrip('\n').split('\t')
        if len(cols) < 2:
            continue
        for m in re.finditer(r'([가-힣]*)([&$%]..@)', cols[1]):
            if m.group(2) not in fam:
                continue
            st, pos, cl = fam[m.group(2)]
            if not st or '(' in st:
                continue
            p = {'Verb': 'V', 'Adjective': 'A'}[pos]
            if cl == 'Existential':
                p = 'X'
            cnt[m.group(1) + st + '다'][p] += 1
print('#! lemmas')
print('# Predicate lemmas and their pos (V verb, A adjective, X 있다/없다), from the 0.7.x dictionaries.')
print('# Generated by tools/build_lemmas.py; stems.tsv rows win over these.')
print('lemma\tpos')
for lemma in sorted(cnt):
    print(lemma + '\t' + cnt[lemma].most_common(1)[0][0])
