#!/usr/bin/env python3
"""Writes the `ending` rows of the 0.7.x lift (poc08/bridge/data/lift-endings.tsv) from the structure
component's decomposition of the 0.7.x ending rows (poc08/structure/data/endings075.tsv).

  poc08/tools/endings2lift.py [--src endings075.tsv] [--out lift-endings.tsv]

A bundle realises the ending on a test host. Its first node is the host: a verb or adjective (then the
features of that node are what the ending sets on the word's own node) or a noun (then the ending is a
copula node and what follows, added after the word). Only rows whose round trip is ok or differs in
spacing are taken.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DROP = {"kind", "lemma", "_hon"}


def node(n, keep_lemma):
    out = {}
    for k, v in n.items():
        if k.startswith("_") or (k in DROP and not (keep_lemma and k in ("kind", "lemma"))):
            continue
        out[k] = v
    ct, rel = out.get("ctype"), out.get("rel")
    if ct in ("adn", "nom", "quote") and rel:
        out["ctype"] = f"{ct}:{rel}"
        del out["rel"]
    if out.get("kase") == "lex":
        out["kase"] = "LEX"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(ROOT / "structure/data/endings075.tsv"))
    ap.add_argument("--out", default=str(ROOT / "bridge/data/lift-endings.tsv"))
    a = ap.parse_args()
    rows = [l.rstrip("\n").split("\t") for l in open(a.src, encoding="utf-8") if not l.startswith("#")]
    head, rows = rows[0], rows[1:]
    out, seen, skipped = [], set(), 0
    for r in rows:
        d = dict(zip(head, r))
        if d.get("rt") not in ("ok", "spacing"):
            skipped += 1
            continue
        try:
            nodes = json.loads(d["bundle"])["nodes"]
        except (ValueError, KeyError):
            skipped += 1
            continue
        if not nodes:
            skipped += 1
            continue
        host = nodes[0]
        if host.get("kind") == "V":
            value = [node(host, False)] + [node(n, True) for n in nodes[1:]]
        else:
            value = [{}] + [node(n, True) for n in nodes[1:]]
        key = (d["key"], d["ko"])
        if key in seen:
            continue
        seen.add(key)
        out.append(f"ending\t{d['key']}\t{d['ko']}\t{json.dumps(value, ensure_ascii=False, separators=(',', ':'))}")
    # Rows by the Korean target alone (key *): the bundle most rows with that target share, when at least
    # 5 rows and 70% of them do (nominal readings excluded: they depend on the key). 0.7.x's own reading already chose the target; these cover the endings of
    # its built-in conjugation tables, which have no row of their own.
    by_ko = {}
    for r in rows:
        d = dict(zip(head, r))
        if d.get("rt") not in ("ok", "spacing"):
            continue
        try:
            nodes = json.loads(d["bundle"])["nodes"]
        except (ValueError, KeyError):
            continue
        if not nodes:
            continue
        host = nodes[0]
        value = ([node(host, False)] if host.get("kind") == "V" else [{}]) + [node(n, True) for n in nodes[1:]]
        sig = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        by_ko.setdefault(d["ko"], {}).setdefault(sig, 0)
        by_ko[d["ko"]][sig] += 1
    fallback = 0
    for ko, sigs in sorted(by_ko.items()):
        total = sum(sigs.values())
        sig, n = max(sigs.items(), key=lambda kv: (kv[1], kv[0]))
        if total >= 5 and n / total >= 0.7 and '"nom:' not in sig and ("*", ko) not in seen:
            out.append(f"ending\t*\t{ko}\t{sig}")
            fallback += 1
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("#! lift\n# Generated by poc08/tools/endings2lift.py from poc08/structure/data/endings075.tsv; do not edit.\n")
        f.write("# ending\t<0.7.x Japanese ending key>\t<0.7.x Korean ending target>\t<features of the word, then added nodes>\n")
        for line in out:
            f.write(line + "\n")
    print(f"{len(out)} ending rows ({fallback} by target alone), {skipped} source rows skipped")


if __name__ == "__main__":
    main()
